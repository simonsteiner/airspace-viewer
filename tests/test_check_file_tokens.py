import subprocess
import sys
from pathlib import Path

import pytest

SCRIPT = Path(__file__).resolve().parent.parent / "scripts/hooks/check-file-tokens.py"
OVER = b"x = 1\n" * 4000  # 6,000 tokens


@pytest.fixture
def repo(tmp_path: Path, monkeypatch: pytest.MonkeyPatch) -> Path:
    # The pre-push hook runs pytest with GIT_DIR and GIT_INDEX_FILE set, which
    # would point git at this repo instead of the temp one.
    for var in ("GIT_DIR", "GIT_INDEX_FILE", "GIT_WORK_TREE"):
        monkeypatch.delenv(var, raising=False)
    subprocess.run(["git", "init", "--quiet", str(tmp_path)], check=True)
    return tmp_path


def _stage(repo: Path, path: str, data: bytes) -> None:
    file = repo / path
    file.parent.mkdir(parents=True, exist_ok=True)
    file.write_bytes(data)
    subprocess.run(["git", "add", "--", path], cwd=repo, check=True)


def _check(repo: Path, *paths: str) -> subprocess.CompletedProcess[str]:
    return subprocess.run(
        [sys.executable, str(SCRIPT), "--max-tokens", "5000", "--", *paths],
        cwd=repo,
        capture_output=True,
        text=True,
    )


def test_over_budget_file_fails_with_split_advice(repo: Path) -> None:
    _stage(repo, "big.py", OVER)
    result = _check(repo, "big.py")
    assert result.returncode == 1
    assert "big.py" in result.stderr + result.stdout
    assert "Split each file" in result.stderr + result.stdout


def test_file_under_budget_passes(repo: Path) -> None:
    _stage(repo, "small.py", b"x = 1\n" * 100)
    assert _check(repo, "small.py").returncode == 0


def test_path_starting_with_dash_is_a_path(repo: Path) -> None:
    _stage(repo, "-n.py", OVER)
    assert _check(repo, "-n.py").returncode == 1


@pytest.mark.parametrize(
    "path",
    ["uv.lock", "app.min.js", "data.csv", "vendor/lib.py", "third_party/x/lib.py"],
)
def test_lockfiles_build_output_data_and_vendor_are_skipped(
    repo: Path, path: str
) -> None:
    _stage(repo, path, OVER)
    assert _check(repo, path).returncode == 0


def test_binary_is_skipped(repo: Path) -> None:
    _stage(repo, "image.bin", b"\0" * 30000)
    assert _check(repo, "image.bin").returncode == 0


@pytest.mark.parametrize(
    "header",
    [b"# @generated\n", b"# Code generated by protoc. DO NOT EDIT.\n"],
)
def test_codegen_header_is_skipped(repo: Path, header: bytes) -> None:
    _stage(repo, "gen.py", header + OVER)
    assert _check(repo, "gen.py").returncode == 0


def test_prose_mentioning_generated_code_is_checked(repo: Path) -> None:
    _stage(repo, "notes.md", b"# Notes\n\nThis file is generated by hand.\n" + OVER)
    assert _check(repo, "notes.md").returncode == 1


def test_gitattributes_mark_counts_only_once_staged(repo: Path) -> None:
    _stage(repo, "examples/big.txt", OVER)
    (repo / ".gitattributes").write_text("examples/** linguist-vendored\n")
    assert _check(repo, "examples/big.txt").returncode == 1
    subprocess.run(["git", "add", ".gitattributes"], cwd=repo, check=True)
    assert _check(repo, "examples/big.txt").returncode == 0


def test_staged_content_is_checked_not_the_working_tree(repo: Path) -> None:
    _stage(repo, "a.py", b"x = 1\n")
    (repo / "a.py").write_bytes(OVER)
    assert _check(repo, "a.py").returncode == 0
    assert _check(repo, "missing.py").returncode == 0
